import db from '../db.ts';
import crypto from 'node:crypto';
import { secret } from '../helpers/env.ts';
import type { Knex } from 'knex';

// This crypt was just created, and doesn't have a verified owner email
export const STATUS_INVALID = 'invalid';
// This crypt has a verified owner email, but recipient or message are missing.
export const STATUS_EMPTY = 'empty';
// This crypt is "armed", and we'll check regularly if the owner is still around
export const STATUS_READY = 'ready';
// This crypt was sent to the intended recipient
export const STATUS_SENT = 'sent';
// This crypt was read by the intended recipient
export const STATUS_READ = 'read';

export type CryptStatus = typeof STATUS_INVALID | typeof STATUS_EMPTY | typeof STATUS_READY | typeof STATUS_SENT | typeof STATUS_READ;

// A row from the `crypts` table
export interface Crypt {
  uuid: string;
  from_name: string;
  from_mail: string;
  to_name: string;
  to_mail: string;
  message: string;
  encrypted_message_name: string;
  encrypted_message: Buffer | null;
  status: CryptStatus;
  times_contacted: number;
  created_at: Date;
  updated_at: Date;
  refreshed_at: Date;
  triggered_at: Date | null;
  read_at: Date | null;
  auth_mail_sent_at: Date | null;
}

// A row from the `crypt_events` audit table
export interface CryptEvent {
  id: number;
  crypt_uuid: string;
  event: string;
  created_at: Date;
  ip: string;
  user_agent: string;
}

// Teach knex about our tables, so every db('crypts') / db('crypt_events') call is typed.
// Insert and update take partial rows, since most queries only touch a subset of columns.
declare module 'knex/types/tables.js' {
  interface Tables {
    crypts: Knex.CompositeTableType<Crypt, Partial<Crypt>, Partial<Crypt>>;
    crypt_events: Knex.CompositeTableType<CryptEvent, Partial<CryptEvent>, Partial<CryptEvent>>;
  }
}

// Actions a crypt link can point to, see routes/crypt.ts
export type CryptAction = 'warnings' | 'verify' | 'verify-from-email' | 'auth-from-email' | 'healthcheck' | 'edit' | '' | 'read';
// Actions that can be signed with a hash, see getCryptHash
export type HashAction = 'verify-email' | 'auth-email' | 'auth';

// How long an authentication cookie stays valid (one week)
export const AUTH_COOKIE_DURATION_MS = 7 * 24 * 60 * 60 * 1000;
// Minimum delay between two authentication emails for a given crypt (anti email-bombing)
export const AUTH_MAIL_COOLDOWN_MS = 15 * 60 * 1000;

// Only the parts of the Koa context that logCryptEvent reads (kept structural so tests can mock it)
type EventContext = { request: { ip: string }; header: { 'user-agent'?: string } };

export const logCryptEvent = async (cryptUuid: string, event: string, ctx: EventContext, trx: Knex = db) => {
  await trx('crypt_events').insert({
    crypt_uuid: cryptUuid,
    event,
    created_at: new Date(),
    ip: ctx.request.ip,
    user_agent: ctx.header['user-agent'] || 'unknown'
  });
};

/**
 * Gets a link for a given crypt and action
 * For instance: /crypts/abc-123/verify-from-email
 */
export const cryptLink = (crypt: Pick<Crypt, 'uuid'>, action: CryptAction): string => `/crypts/${crypt.uuid}/${action}`;

/**
 * Generate a unique hash for a given action, with expiration time.
 * This can then be validated through @validateCryptHash
 * @param validUntil timestamp until which this token should be valid (one year by default)
 */
export const getCryptHash = (crypt: Pick<Crypt, 'uuid'>, action: HashAction, payload: string, validUntil: number = Date.now() + 60 * 60 * 24 * 365 * 1000) => {
  // JSON.stringify gives an unambiguous, injective encoding of the fields, so a value
  // containing a delimiter (e.g. an email address holding '@') can't shift field boundaries.
  const toHash = JSON.stringify([crypt.uuid, action, payload, validUntil]);
  // HMAC (rather than a raw secret-prefixed SHA-256) is immune to length-extension attacks.
  const hash = crypto.createHmac('sha256', secret).update(toHash).digest('hex');

  return {
    hash,
    validUntil
  };
};

/**
 * Validate a hash generated by @getCryptHash.
 * `hash` and `validUntil` are user input (query string / cookie), hence `unknown`.
 */
export const validateCryptHash = (crypt: Pick<Crypt, 'uuid'>, action: HashAction, payload: string, hash: unknown, validUntil: unknown): boolean => {
  validUntil = Number(validUntil);
  if (!(typeof validUntil === 'number' && validUntil > Date.now()) || typeof hash !== 'string') {
    return false;
  }
  const validHash = getCryptHash(crypt, action, payload, validUntil);
  // Constant-time comparison to avoid leaking the expected hash through timing.
  // Compare byte lengths (not string lengths: multibyte input differs), as timingSafeEqual throws on mismatched buffer lengths.
  const hashBuffer = Buffer.from(hash);
  const validHashBuffer = Buffer.from(validHash.hash);
  if (hashBuffer.length !== validHashBuffer.length) {
    return false;
  }
  return crypto.timingSafeEqual(hashBuffer, validHashBuffer);
};

/**
 * Build the week-long authentication cookie for a crypt owner.
 * The uuid and expiry are baked into the hash input, so a cookie copied from
 * another crypt or with a tampered expiry will fail validation.
 */
export const getAuthCookie = (crypt: Pick<Crypt, 'uuid' | 'from_mail'>) => {
  const { hash, validUntil } = getCryptHash(crypt, 'auth', crypt.from_mail, Date.now() + AUTH_COOKIE_DURATION_MS);
  return {
    name: `auth-${crypt.uuid}`,
    value: `${hash}.${validUntil}`,
    validUntil
  };
};

/**
 * Validate an authentication cookie value (`<hash>.<validUntil>`) against a crypt.
 */
export const isValidAuthCookie = (crypt: Pick<Crypt, 'uuid' | 'from_mail'>, cookieValue: unknown): boolean => {
  if (!cookieValue || typeof cookieValue !== 'string') {
    return false;
  }
  // sha256 hex digests contain no '.', so the split is unambiguous.
  const [hash, validUntil] = cookieValue.split('.');
  return validateCryptHash(crypt, 'auth', crypt.from_mail, hash, validUntil);
};
